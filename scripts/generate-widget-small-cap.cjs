const fs = require('node:fs');
const path = require('node:path');

// Freeze the existing two-row proportions at the height of the approved preview.
// Rows keep wrap_content so long names and larger fonts can still take more space.
const capHeight = 180;
const root = path.join(__dirname, '../src/uni_modules/lakeside-widget/utssdk/app-android/res');
const source = fs.readFileSync(path.join(root, 'layout/ls_widget_small.xml'), 'utf8');
const attributes = tag => Object.fromEntries([...tag.matchAll(/android:([\w]+)="([^"]*)"/g)].map(match => [match[1], match[2]]));
const tags = [...source.matchAll(/<LinearLayout\b[^>]*>/g)].map(match => attributes(match[0]));
const number = value => {
  const result = Number(String(value).replace(/dp$/, ''));
  if (!Number.isFinite(result)) throw new Error('Unsupported small widget dimension: ' + value);
  return result;
};
const rows = tags.filter(tag => tag.minHeight && tag.orientation === 'horizontal');
const courseGaps = tags.filter(tag => tag.id?.startsWith('@+id/ls_small_course_gap'));
const edges = tags.filter(tag => tag.id?.startsWith('@+id/ls_small_edge_gap'));
if (rows.length !== 4 || courseGaps.length !== 3 || edges.length !== 2) throw new Error('Unexpected two-row widget structure');
const [outer, header, body] = tags;
const totalWeight = [...rows, ...courseGaps, ...edges].reduce((sum, tag) => sum + number(tag.layout_weight), 0);
const available = capHeight - number(outer.paddingTop) - number(outer.paddingBottom) - number(header.layout_height) - number(body.minHeight);
if (available < 0 || totalWeight <= 0) throw new Error('Two-row widget cannot fit its spacing ceiling');
const share = available / totalWeight;
const dp = value => Number(value.toFixed(3)) + 'dp';
function set(tag, name, value) {
  const key = new RegExp(' android:' + name + '="[^"]*"');
  if (value === null) return tag.replace(key, '');
  return key.test(tag) ? tag.replace(key, ' android:' + name + '="' + value + '"') : tag.replace('<LinearLayout', '<LinearLayout android:' + name + '="' + value + '"');
}
let index = 0;
let capped = source.replace(/<LinearLayout\b[^>]*>/g, tag => {
  const a = attributes(tag), position = index++;
  if (position === 0 || position === 2) {
    tag = set(tag, 'layout_height', 'wrap_content');
    tag = set(tag, 'layout_weight', null);
    if (position === 0) tag = set(tag, 'id', '@+id/ls_small_capped_content');
  } else if (a.minHeight && a.orientation === 'horizontal') {
    tag = set(tag, 'minHeight', dp(number(a.minHeight) + share * number(a.layout_weight)));
    tag = set(tag, 'layout_weight', null);
  } else if (a.id?.startsWith('@+id/ls_small_content')) {
    tag = set(tag, 'layout_height', 'wrap_content');
  } else if (a.id?.startsWith('@+id/ls_small_course_gap') || a.id?.startsWith('@+id/ls_small_edge_gap') || a.id?.startsWith('@+id/ls_small_line_gap')) {
    tag = set(tag, 'layout_height', dp(number(a.layout_height) + share * number(a.layout_weight)));
    tag = set(tag, 'layout_weight', null);
  }
  return tag;
});
// Reuse the first fixed-spacing course for every additional row. Its IDs are
// scoped to the nested RemoteViews, so clicks and status lamps remain independent.
const opening = [...capped.matchAll(/<LinearLayout\b[^>]*>/g)].find(match => {
  const a = attributes(match[0]);
  return a.minHeight && a.orientation === 'horizontal';
});
let depth = 0, rowEnd;
for (const token of capped.slice(opening.index).matchAll(/<LinearLayout\b[^>]*>|<\/LinearLayout>/g)) {
  if (token[0].startsWith('</')) depth--;
  else if (!token[0].endsWith('/>')) depth++;
  if (depth === 0) { rowEnd = opening.index + token.index + token[0].length; break; }
}
if (!rowEnd) throw new Error('Cannot extract compact course row');
const row = capped.slice(opening.index, rowEnd);
const extraGap = number(courseGaps[0].layout_height) + share * number(courseGaps[0].layout_weight);
const rowMinimum = number(rows[0].minHeight) + share * number(rows[0].layout_weight);
const extraRow = '<!-- Generated by scripts/generate-widget-small-cap.cjs. -->\n<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android" android:id="@+id/ls_small_extra_row" android:layout_width="match_parent" android:layout_height="wrap_content" android:orientation="vertical" android:clipChildren="false">\n<LinearLayout android:layout_width="match_parent" android:layout_height="' + dp(extraGap) + '" />\n' + row + '\n</LinearLayout>\n';
capped = capped.replace(/(<LinearLayout android:id="@\+id\/ls_small_edge_gap_bottom")/, '<LinearLayout android:id="@+id/ls_small_more_courses" android:layout_width="match_parent" android:layout_height="wrap_content" android:orientation="vertical" android:clipChildren="false" android:visibility="gone" />\n      $1');
function save(name, content) {
  const file = path.join(root, name);
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return false;
  fs.writeFileSync(file, content);
  return true;
}
const layoutChanged = save('layout/ls_widget_small_capped.xml', '<!-- Generated by scripts/generate-widget-small-cap.cjs; edit the adaptive layout instead. -->\n' + capped);
const rowChanged = save('layout/ls_widget_small_extra_row.xml', extraRow);
const nameTag = attributes([...source.matchAll(/<TextView\b[^>]*>/g)].find(m => attributes(m[0]).id === '@+id/ls_small_name')[0]);
const metaTag = attributes([...source.matchAll(/<TextView\b[^>]*>/g)].find(m => attributes(m[0]).id === '@+id/ls_small_meta')[0]);
const labelTag = attributes([...source.matchAll(/<TextView\b[^>]*>/g)].find(m => attributes(m[0]).id === '@+id/ls_small_label')[0]);
const statusTag = attributes([...source.matchAll(/<FrameLayout\b[^>]*>/g)].find(m => attributes(m[0]).id === '@+id/ls_small_status')[0]);
const accentTag = attributes([...source.matchAll(/<ImageView\b[^>]*>/g)].find(m => attributes(m[0]).id === '@+id/ls_small_accent')[0]);
const contentTag = tags.find(a => a.id === '@+id/ls_small_content');
const sizes = {
  ls_widget_small_spacing_cap: capHeight + 'dp',
  ls_widget_small_row_min: dp(rowMinimum), ls_widget_small_course_gap: dp(extraGap),
  ls_widget_small_line_gap: dp(number(tags.find(a => a.id === '@+id/ls_small_line_gap').layout_height) + share),
  ls_widget_small_chrome: dp(number(outer.paddingTop) + number(outer.paddingBottom) + number(header.layout_height) + edges.reduce((sum,a) => sum + share * number(a.layout_weight),0)),
  ls_widget_small_text_inset: dp(number(outer.paddingStart) + number(outer.paddingEnd) + number(body.paddingStart) + number(accentTag.layout_width) + number(contentTag.layout_marginStart)),
  ls_widget_small_title_inset: dp(number(statusTag.layout_width) + number(statusTag.layout_marginEnd)),
  ls_widget_small_title_min: statusTag.layout_height,
  ls_widget_small_label_margin: labelTag.layout_marginEnd,
  ls_widget_small_name_size: nameTag.textSize, ls_widget_small_meta_size: metaTag.textSize, ls_widget_small_label_size: labelTag.textSize,
};
const sizeChanged = save('values/widget_spacing.xml', '<!-- Generated by scripts/generate-widget-small-cap.cjs. -->\n<resources>\n' + Object.entries(sizes).map(([name,value]) => '  <dimen name="'+name+'">'+value+'</dimen>').join('\n') + '\n</resources>\n');
if (layoutChanged || rowChanged || sizeChanged || require.main === module) console.log('Generated fixed small-widget spacing and additional course rows above ' + capHeight + 'dp.');
