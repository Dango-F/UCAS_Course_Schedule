const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const out = path.resolve('.artifacts/screenshots');
  fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const errors = [], checks = [], dimensions = [];
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  page.on('pageerror', e => errors.push(e.message));
  const shot = async name => { await page.screenshot({ path: path.join(out, name + '.png'), fullPage: true, animations: 'disabled' }); };
  const close = async () => { await page.locator('.sheet-backdrop .close-button').click(); await page.locator('.sheet-backdrop').waitFor({state:'hidden'}); };
  const setting = async label => { await page.locator('[aria-label="预览设置"]').click(); await page.locator('.scenario-option').filter({hasText:label}).click(); };
  await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' });
  await page.locator('.course-tile').first().waitFor();
  assert.ok((await page.locator('.course-tile .tile-teacher').first().innerText()).trim(), 'Course cards show teacher');
  checks.push('课程卡片显示任课教师');
  for (const width of [360,390,430]) {
    await page.setViewportSize({ width, height:844 });
    await page.locator('.month-title').waitFor();
    await shot(`home-${width}`);
    dimensions.push(await page.evaluate(() => ({ width:innerWidth, documentWidth:document.documentElement.scrollWidth, bodyHeight:document.body.scrollHeight, canvasHeight:document.querySelector('.phone-canvas').getBoundingClientRect().height, buttonBorder:getComputedStyle(document.querySelector('.icon-button'),'::after').borderWidth, tiles:[...document.querySelectorAll('.course-tile')].map(el=>({width:el.getBoundingClientRect().width,height:el.getBoundingClientRect().height})) })));
    assert.equal(dimensions.at(-1).documentWidth,width,`No horizontal overflow at ${width}`);
    assert.ok(dimensions.at(-1).tiles.every(tile=>tile.width >= 44 && tile.height >= 44),`Course touch targets at ${width}`);
  }
  checks.push('360/390/430px 无页面横向溢出');
  await page.setViewportSize({width:390,height:844});
  await page.locator('.course-tile').filter({hasText:'矩阵分析'}).first().click();
  await page.locator('.detail-title').waitFor();
  assert.equal(await page.locator('.meeting-card').count(),2);
  await shot('course-detail');
  checks.push('课程详情保留两个上课时段');
  await page.locator('.detail-actions .primary-button').click();
  await page.locator('.edit-form input').first().fill('矩阵分析 · 已编辑');
  await page.locator('.edit-form .primary-button').click();
  assert.match(await page.locator('.detail-title').innerText(),/已编辑/);
  await close();
  assert.equal(await page.locator('.course-tile').filter({hasText:'已编辑'}).count(),2);
  checks.push('编辑课程名称同步到全部课表时段');
  await page.locator('[aria-label="下一周"]').click();
  assert.match(await page.locator('.week-select').innerText(),/02/);
  assert.equal(await page.locator('.course-tile').filter({hasText:'科学计算'}).count(),0);
  await page.locator('.week-select').click();
  await shot('week-picker');
  await page.locator('.week-option').first().click();
  checks.push('切周正确过滤单周课程，周选择器可返回');
  await setting('课程冲突');
  await shot('conflict-home');
  await page.locator('.course-tile.conflict').click();
  assert.equal(await page.locator('.conflict-item').count(),2);
  await shot('conflict-detail');
  await page.locator('.conflict-item').last().click();
  assert.match(await page.locator('.detail-title').innerText(),/学术道德/);
  await shot('long-course-detail');
  await close();
  checks.push('重叠课程可展开，两门详情均可访问');
  await setting('密集课表');
  await shot('dense-home');
  await page.locator('.calendar-scroll .uni-scroll-view').evaluateAll(elements=>{for(const el of elements)el.scrollTop=el.scrollHeight});
  await shot('dense-evening');
  await setting('空课表');
  await shot('empty-home');
  await page.locator('.empty-state .primary-button').click();
  await page.locator('.import-title').waitFor();
  await shot('import-intro');
  assert.match(await page.locator('.status-note').innerText(),/网页预览不接入学校登录/);
  await page.locator('.import-content .primary-button').click();
  await page.locator('.empty-demo').click();
  checks.push('空课表导入入口及返回示例可用，H5 未伪装真实导入');
  await page.locator('.nav-item').filter({hasText:'今日'}).click();
  await shot('today');
  await close();
  await page.locator('.nav-item').filter({hasText:'学期'}).click();
  await shot('semester');
  await close();
  await page.locator('[aria-label="预览设置"]').click();
  await page.locator('.preference-row').click();
  assert.equal(await page.locator('.toggle.on').count(),1);
  await shot('settings');
  await page.keyboard.press('Escape');
  await page.locator('.sheet-backdrop').waitFor({state:'hidden'});
  await page.setViewportSize({width:1280,height:960});
  await shot('desktop');
  checks.push('今日、学期、减少动画与桌面预览可用');
  assert.deepEqual(errors,[]);
  const result = { checkedAt:new Date().toISOString(),checks,errors,dimensions };
  fs.writeFileSync(path.join(out,'report.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify({checks,errors,screenshotDirectory:out},null,2));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
